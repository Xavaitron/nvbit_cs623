#include <stdint.h>
#include "utils/utils.h"
#include "utils/channel.hpp"
#include "common.h"
extern "C" __device__ __noinline__
void instrument_pc(uint64_t pc, uint64_t pchannel_dev) {
    // Ignore predicates: all lanes reaching this instruction participate.
    const unsigned mask = __ballot_sync(__activemask(), 1);
    const int leader = __ffs(mask) - 1;
    if (get_laneid() == leader) {
        pc_access_t record;
        record.pc = pc;
        ChannelDev *channel = (ChannelDev *)pchannel_dev;
        channel->push(&record, sizeof(record));
    }
}
